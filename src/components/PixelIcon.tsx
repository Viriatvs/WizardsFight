export type PixelIconName = keyof typeof ICONS;

const SIZE = 16;

/** One pixel icon. With a label it's announced as an image; without, it's decorative. Sized in px, or 1em to follow the text. */
export default function PixelIcon({ name, size = '1em', label, className }: { name: PixelIconName; size?: number | string; label?: string; className?: string }) {
  const { pixels, colors } = ICONS[name];
  const palette: Record<string, string> = colors;
  return (
    <svg
      viewBox={`0 0 ${SIZE} ${SIZE}`}
      width={size}
      height={size}
      shapeRendering="crispEdges"
      className={`inline-block align-[-0.15em] ${className ?? ''}`}
      {...(label ? { role: 'img', 'aria-label': label } : { 'aria-hidden': true })}
    >
      {pixels.flatMap((row, y) =>
        [...row].flatMap((c, x) => (c === '.' ? [] : [<rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={palette[c]} />])),
      )}
    </svg>
  );
}

